/**
 * Готовая кнопка «Совет куда ехать».
 *
 * Владелец, 21.10.2026: кнопка отправляла «Не знаю куда поехать в сентябре с
 * ребёнком 5 лет — что посоветуете?» — это выдуманные данные (месяц, ребёнок,
 * возраст), которых клиент не говорил. Кнопка должна отправлять просьбу без
 * подробностей, а Мила — сама спросить, когда, откуда и кто едет.
 *
 * Новые версии виджета (@tosmedia/ai-assistant 1.0.19, -native 1.2.3, мобильный
 * чат сайта) отправляют ADVICE. Пока сайт и приложения не обновлены, старые
 * тексты этой кнопки сервер заменяет на ADVICE. Меняются только ровно эти
 * готовые тексты — всё, что клиент написал сам, остаётся как есть.
 */
export const ADVICE = 'Посоветуйте, куда поехать в отпуск'

const LEGACY_ADVICE = new Set([
  'Не знаю куда поехать в сентябре с ребёнком 5 лет — что посоветуете?',
  'Не знаю куда поехать с ребёнком 5 лет — что посоветуете?',
])

export function normalizeQuickPrompt(text: string): string {
  return LEGACY_ADVICE.has(text.trim()) ? ADVICE : text
}
