#!/usr/bin/env node
/**
 * docs/playbook/*.json → server/agentPlaybookData.ts («опыт турагента»).
 * Edit the JSON (or add a file), then: node scripts/build-playbook.mjs
 * Validates every topic; exits with an error instead of writing bad data.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'docs', 'playbook')
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
const all = []
const errors = []
const ids = new Set()
const MAX = 260

// Triggers that are too common to pick a topic on their own («маршрут»,
// «документ», «экскурсия» — frequent in the owner's 500 requests across
// unrelated topics). Such a trigger counts half.
const GENERIC = ['месяц', 'маленьк', 'доплат', 'документ', 'паспорт', 'ресторан', 'экскурс', 'маршрут', 'сравни', 'безопасн', 'кухн', 'аренд', 'багаж', 'лестниц', 'отел', 'номер', 'пляж', 'море', 'тур', 'дет', 'ребен']
const isWeak = (trig) => GENERIC.some((g) => trig.startsWith(g))

// The placeholder phone must never reach the prompt, not even as an example
// of a mistake — the model would repeat it.
const clean = (x) => String(x).replace(/\s*\(?\+?7?\s*\(?8?800\)?\s*000-00-00\)?/g, '').replace(/\s{2,}/g, ' ').trim()
const strList = (v) => (Array.isArray(v) ? v.map(clean).filter(Boolean) : [])

for (const f of files) {
  const list = JSON.parse(readFileSync(path.join(dir, f), 'utf8'))
  if (!Array.isArray(list)) {
    errors.push(`${f}: ожидается массив тем`)
    continue
  }
  for (const t of list) {
    const id = String(t.id ?? '').trim()
    const where = `${f} → ${id || '(без id)'}`
    if (!/^[a-z0-9-]+$/.test(id)) errors.push(`${where}: id только латиница, цифры, дефис`)
    if (ids.has(id)) errors.push(`${where}: id повторяется`)
    ids.add(id)
    const topic = {
      id,
      title: String(t.title ?? '').trim(),
      triggers: [...new Set(strList(t.triggers).map((x) => x.toLowerCase().replace(/ё/g, 'е')))],
      ask: strList(t.ask),
      advise: strList(t.advise),
      facts: (Array.isArray(t.facts) ? t.facts : [])
        .map((x) => (typeof x === 'string' ? { text: x } : { text: clean(x.text ?? ''), source: x.source ? String(x.source) : undefined }))
        .filter((x) => x.text),
      operator: strList(t.operator),
      avoid: strList(t.avoid),
    }
    topic.weak = topic.triggers.filter(isWeak)
    if (!topic.title) errors.push(`${where}: нет title`)
    if (topic.triggers.length < 3) errors.push(`${where}: меньше 3 triggers`)
    for (const tr of topic.triggers) if (tr.length < 3) errors.push(`${where}: trigger «${tr}» короче 3 букв`)
    if (!topic.advise.length) errors.push(`${where}: нет advise`)
    for (const fct of topic.facts) if (!/^https?:\/\//.test(fct.source ?? '')) errors.push(`${where}: факт без источника «${fct.text.slice(0, 50)}»`)
    for (const k of ['ask', 'advise', 'operator', 'avoid']) {
      for (const line of topic[k]) if (line.length > MAX) errors.push(`${where}: ${k} длиннее ${MAX}: «${line.slice(0, 60)}…»`)
    }
    for (const fct of topic.facts) if (fct.text.length > MAX) errors.push(`${where}: fact длиннее ${MAX}: «${fct.text.slice(0, 60)}…»`)
    all.push(topic)
  }
}

if (errors.length) {
  console.error(`build-playbook: ${errors.length} ошибок\n` + errors.map((e) => `  ✗ ${e}`).join('\n'))
  process.exit(1)
}

// Sources stay in docs/playbook/*.json for review; the server needs only the text.
const forServer = all.map((t) => ({ ...t, facts: t.facts.map((f) => ({ text: f.text })) }))
const out = `/** Generated by scripts/build-playbook.mjs from docs/playbook/*.json — do not edit by hand. */
export type Playbook = {
  id: string
  title: string
  triggers: string[]
  ask: string[]
  advise: string[]
  facts: Array<{ text: string }>
  operator: string[]
  avoid: string[]
  /** Triggers that count half: too common to choose the topic alone. */
  weak: string[]
}

export const PLAYBOOKS: Playbook[] = ${JSON.stringify(forServer, null, 2)}
`
writeFileSync(path.join(root, 'server', 'agentPlaybookData.ts'), out)
console.log(`build-playbook: ${all.length} тем из ${files.length} файлов → server/agentPlaybookData.ts`)
