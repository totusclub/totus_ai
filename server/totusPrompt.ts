function formatCurrentDate(date = new Date()) {
  return new Intl.DateTimeFormat('ru-RU', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    weekday: 'long',
  }).format(date)
}

export function totusConfig() {
  return {
    agentName: process.env.TOTUS_AGENT_NAME || 'Мила',
    companyPhone: process.env.TOTUS_COMPANY_PHONE || '+7 (800) 000-00-00',
    promoInfo: process.env.TOTUS_PROMO_INFO || '',
    departureCities:
      process.env.TOTUS_DEPARTURE_CITIES ||
      'Москва, Санкт-Петербург, Казань, Екатеринбург, Новосибирск',
  }
}

/** If company works with a single departure city, return it; otherwise null. */
export function singleDepartureCity() {
  const cities = totusConfig()
    .departureCities.split(',')
    .map((c) => c.trim())
    .filter(Boolean)
  return cities.length === 1 ? cities[0] : null
}

export function buildTotusSystemPrompt(now = new Date()) {
  const cfg = totusConfig()
  const promo = cfg.promoInfo.trim() || 'Акций сейчас нет.'

  return TOTUS_PROMPT_TEMPLATE.replaceAll('{CURRENT_DATE}', formatCurrentDate(now))
    .replaceAll('{AGENT_NAME}', cfg.agentName)
    .replaceAll('{COMPANY_PHONE}', cfg.companyPhone)
    .replaceAll('{PROMO_INFO}', promo)
    .replaceAll('{DEPARTURE_CITIES}', cfg.departureCities)
}
