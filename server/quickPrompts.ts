/**
 * Готовая кнопка «Совет куда ехать» в старых версиях виджета (сайт до
 * @tosmedia/ai-assistant 1.0.18, приложение до -native 1.2.2) отправляла
 * «Не знаю куда поехать в сентябре…». Владелец, 21.10.2026: сентябрь уже прошёл,
 * убрать. В новых версиях кнопка без месяца; пока сайт и приложения не
 * обновлены, сервер убирает месяц из этого готового текста сам.
 * Меняется только ровно этот текст кнопки — всё, что клиент написал сам, как есть.
 */
const LEGACY_ADVICE = 'Не знаю куда поехать в сентябре с ребёнком 5 лет — что посоветуете?'
const ADVICE = 'Не знаю куда поехать с ребёнком 5 лет — что посоветуете?'

export function normalizeQuickPrompt(text: string): string {
  return text.trim() === LEGACY_ADVICE ? ADVICE : text
}
